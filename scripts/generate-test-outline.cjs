#!/usr/bin/env node
// Regenerates docs/test-suite-outline.md from every describe/it title in
// src/**/*.test.ts(x). Run via `npm run docs:test-outline`; also run
// automatically by .github/workflows/test-outline.yml on pushes to main.
const fs = require('fs');
const path = require('path');
const ts = require('typescript');

const ROOT_DIR = path.join(__dirname, '..');
const SRC_DIR = path.join(ROOT_DIR, 'src');
const OUTPUT_FILE = path.join(ROOT_DIR, 'docs', 'test-suite-outline.md');

function findTestFiles(dir) {
  const results = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      results.push(...findTestFiles(full));
    } else if (/\.test\.tsx?$/.test(entry.name)) {
      results.push(full);
    }
  }
  return results;
}

function isCallTo(node, name) {
  if (!ts.isCallExpression(node)) return false;
  const expr = node.expression;
  if (ts.isIdentifier(expr) && expr.text === name) return true;
  // matches describe.skip(...), it.only(...), it.each(...), etc.
  if (
    ts.isPropertyAccessExpression(expr) &&
    ts.isIdentifier(expr.expression) &&
    expr.expression.text === name
  ) {
    return true;
  }
  return false;
}

function getFirstStringArgText(node) {
  const arg = node.arguments[0];
  if (!arg) return null;
  if (ts.isStringLiteral(arg) || ts.isNoSubstitutionTemplateLiteral(arg)) {
    return arg.text;
  }
  if (ts.isTemplateExpression(arg)) {
    let out = arg.head.text;
    for (const span of arg.templateSpans) {
      out += '${...}' + span.literal.text;
    }
    return out;
  }
  return null;
}

/** Extracts a tree of {title, kind: 'describe'|'it', children} from one test file's describe/it calls, in source order. */
function extractOutline(filePath) {
  const sourceText = fs.readFileSync(filePath, 'utf8');
  const sourceFile = ts.createSourceFile(
    filePath,
    sourceText,
    ts.ScriptTarget.Latest,
    true,
    filePath.endsWith('.tsx') ? ts.ScriptKind.TSX : ts.ScriptKind.TS,
  );

  const root = { title: null, kind: 'root', children: [] };
  const stack = [root];

  function visit(node) {
    let pushed = false;
    if (isCallTo(node, 'describe')) {
      const title = getFirstStringArgText(node) ?? '(dynamic describe title)';
      const entry = { title, kind: 'describe', children: [] };
      stack[stack.length - 1].children.push(entry);
      stack.push(entry);
      pushed = true;
    } else if (isCallTo(node, 'it') || isCallTo(node, 'test')) {
      const title = getFirstStringArgText(node) ?? '(dynamic test title)';
      const entry = { title, kind: 'it', children: [] };
      stack[stack.length - 1].children.push(entry);
      stack.push(entry);
      pushed = true;
    }

    ts.forEachChild(node, visit);

    if (pushed) stack.pop();
  }

  visit(sourceFile);
  return root.children;
}

function escapeMd(text) {
  // Backslash first, so an existing backslash in the title (e.g. right
  // before one of the other special characters) doesn't itself absorb the
  // escaping we're about to add for that character.
  return text.replace(/\\/g, '\\\\').replace(/([*_`[\]])/g, '\\$1');
}

function renderNode(node, depth) {
  const indent = '  '.repeat(depth);
  const bullet = node.kind === 'describe' ? `**${escapeMd(node.title)}**` : escapeMd(node.title);
  let out = `${indent}- ${bullet}\n`;
  for (const child of node.children) {
    out += renderNode(child, depth + 1);
  }
  return out;
}

function githubAnchor(headingText) {
  return headingText
    .toLowerCase()
    .replace(/[^a-z0-9 -]/g, '')
    .replace(/\s+/g, '-');
}

function main() {
  const files = findTestFiles(SRC_DIR)
    .map((file) => path.relative(ROOT_DIR, file))
    .sort();
  const outlinesByFile = Object.fromEntries(
    files.map((file) => [file, extractOutline(path.join(ROOT_DIR, file))]),
  );

  let totalTests = 0;
  function countIt(nodes) {
    for (const n of nodes) {
      if (n.kind === 'it') totalTests += 1;
      countIt(n.children);
    }
  }
  for (const file of files) countIt(outlinesByFile[file]);

  let md = '';
  md += '# Test Suite Outline\n\n';
  md += `Every \`*.test.ts\`/\`*.test.tsx\` file in the repo, with every \`describe\`/\`it\` title, transcribed from the source. Covers ${files.length} files and ${totalTests} tests as of the last regeneration.\n\n`;
  md +=
    'Coverage results for these tests are uploaded to [Codecov](https://app.codecov.io/gh/carpiediem/spoiler-maps) by the [CI workflow](../.github/workflows/ci.yml) on every push to `main` and every pull request. This file itself is regenerated by the [Test Outline workflow](../.github/workflows/test-outline.yml) on every push to `main` — run `npm run docs:test-outline` to update it locally.\n\n';
  md += '## Table of Contents\n\n';
  for (const file of files) {
    md += `- [${file}](#${githubAnchor(file)})\n`;
  }
  md += '\n';

  for (const file of files) {
    md += `## ${file}\n\n`;
    for (const node of outlinesByFile[file]) {
      md += renderNode(node, 0);
    }
    md += '\n';
  }

  fs.writeFileSync(OUTPUT_FILE, md);
  console.log(
    `Wrote ${path.relative(ROOT_DIR, OUTPUT_FILE)} (${files.length} files, ${totalTests} tests).`,
  );
}

main();
